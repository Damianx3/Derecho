export function translate(language, key, values = {}) {
  const text = STRINGS[language]?.[key] ?? STRINGS.English[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => String(values[name] ?? match));
}

// Map known backend errors to local text. Keep protocol details in server logs.
export function translateError(language, message) {
  let key = 'genericError';
  if (/Cannot (reach|connect)|Failed to fetch/i.test(message)) key = 'connectionError';
  else if (/Volume was not applied/i.test(message)) key = 'volumeError';
  else if (/Microphone|recording|record audio/i.test(message)) key = 'recordingError';
  else if (/No translated audio/i.test(message)) key = 'noAudioError';
  else if (/already|current operation/i.test(message)) key = 'busyError';
  else if (/empty transcript/i.test(message)) key = 'transcriptError';
  else if (/Piper|Speaker playback|voice|16-bit PCM/i.test(message)) key = 'speechError';
  else if (/Gemma|translation|Whisper/i.test(message)) key = 'translationError';
  return translate(language, key);
}
